export const dictionaries: Record<Lang, Record<Key, string>> = { id, en };
const fill = (text: string, vars?: Record<string, string | number>) =>
  vars ? text.replace(/\{(\w+)\}/g, (match, name: string) => name in vars ? String(vars[name]) : match) : text;

interface LangContext { lang: Lang; t: (key: Key, vars?: Record<string, string | number>) => string; setLang: (lang: Lang) => void }
const Context = createContext<LangContext | null>(null);

export function LangProvider({ initial, children }: { initial: Lang; children: React.ReactNode }) {
  const [lang, setState] = useState<Lang>(initial);
  const setLang = useCallback((next: Lang) => {
    setState(next);
    document.documentElement.lang = next;
    const secure = window.location.protocol === 'https:' ? '; Secure' : '';
    document.cookie = `${LANG_COOKIE}=${next}; Path=/; Max-Age=31536000; SameSite=Lax${secure}`;
  }, []);
  const value = useMemo<LangContext>(() => ({ lang, setLang, t: (key, vars) => fill(dictionaries[lang][key], vars) }), [lang, setLang]);
  return <Context.Provider value={value}>{children}</Context.Provider>;
}

export function useLang() {
  const value = useContext(Context);
  if (!value) throw new Error('useLang needs LangProvider');
  return value;
}

/** Notice from the shared auth flow, in the interface language. */
export function noticeText(lang: Lang, notice: string) { return lang === 'en' ? enNotices[notice] ?? notice : notice; }
/** Error from the shared auth flow or the API, in the interface language. */
export function authErrorText(lang: Lang, code: string, message: string) {
  return lang === 'en' ? enAuthErrors[code] ?? en['err.default'] : message;
}

export function LangSwitch() {
  const { lang, setLang, t } = useLang();
  return <div className="lang" role="group" aria-label={t('lang.label')}>
    {(['id', 'en'] as const).map(option => <button key={option} type="button" className={lang === option ? 'on' : ''} aria-pressed={lang === option} onClick={() => setLang(option)} lang={option}>{option.toUpperCase()}</button>)}
  </div>;
}
